// emailNoticeMore are the 28 lines of the account notices (a new approver, a relinked phone,
// a pack or a raise asked for, who joined, a Card changed, separation of duties turned off) in
// the languages beyond the eight, laid over each language's core lines. First drafts for each
// language's owner to correct. A language reads its notices once it has both groups.
func init() {
	for code, lines := range emailNoticeMore {
		core, ok := EmailMore[code]
		if !ok {
			continue
		}
		for k, v := range lines {
			core[k] = v
		}
	}
}

